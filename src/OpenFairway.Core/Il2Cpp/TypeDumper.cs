using System;
using System.IO;
using System.Text;

namespace OpenFairway.Core.Il2Cpp;

/// <summary>
/// Writes one C#-like signature file per game assembly by asking the running game's own reflection API.
/// Output is names, offsets and signatures only (no code), and is for local development: do not redistribute it.
/// </summary>
internal static unsafe class TypeDumper
{
    private const string StampFile = "_build.txt";

    public static bool IsCurrent(string dumpDir, string gameDir)
    {
        var stamp = Path.Combine(dumpDir, StampFile);
        return File.Exists(stamp) && File.ReadAllText(stamp).Trim() == BuildId(gameDir);
    }

    public static void Dump(string dumpDir, string gameDir)
    {
        Directory.CreateDirectory(dumpDir);
        long classes = 0, methods = 0;
        foreach (var (name, image) in GameRuntime.Images())
        {
            var count = Native.image_get_class_count(image);
            Log.Info($"  dumping {name} ({count} types)");
            using var w = new StreamWriter(Path.Combine(dumpDir, Path.ChangeExtension(name, ".cs")), false, Encoding.UTF8);
            w.WriteLine($"// {name} - generated by OpenFairway from the running game. Local use only.");
            for (nuint i = 0; i < count; i++)
            {
                var klass = Native.image_get_class(image, i);
                if (klass == IntPtr.Zero) continue;
                methods += WriteClass(w, klass);
                classes++;
            }
        }
        File.WriteAllText(Path.Combine(dumpDir, StampFile), BuildId(gameDir));
        Log.Info($"  {classes} types, {methods} methods");
    }

    private static int WriteClass(StreamWriter w, IntPtr klass)
    {
        var isEnum = Native.class_is_enum(klass) != 0;
        var kind = isEnum ? "enum" : Native.class_is_interface(klass) != 0 ? "interface" : Native.class_is_valuetype(klass) != 0 ? "struct" : "class";
        var parent = Native.class_get_parent(klass);
        var ns = Native.Str(Native.class_get_namespace(klass));

        w.WriteLine();
        if (ns.Length > 0) w.WriteLine($"// Namespace: {ns}");
        w.Write($"{kind} {Native.TypeName(Native.class_get_type(klass))}");
        if (parent != IntPtr.Zero && kind == "class") w.Write($" : {Native.TypeName(Native.class_get_type(parent))}");
        w.WriteLine();
        w.WriteLine("{");

        IntPtr iter = IntPtr.Zero, field;
        while ((field = Native.class_get_fields(klass, &iter)) != IntPtr.Zero)
        {
            var flags = Native.field_get_flags(field);
            var isStatic = (flags & 0x10) != 0;
            var isLiteral = (flags & 0x40) != 0;
            var fieldName = Native.Str(Native.field_get_name(field));
            if (isEnum && isLiteral)
            {
                long value = 0;
                Native.field_static_get_value(field, &value);
                w.WriteLine($"    {fieldName} = {value},");
                continue;
            }
            var mods = Access(flags) + (isLiteral ? " const" : isStatic ? " static" : "");
            w.WriteLine($"    {mods} {Native.TypeName(Native.field_get_type(field))} {fieldName}; // 0x{(ulong)Native.field_get_offset(field):X}");
        }

        var methodCount = 0;
        iter = IntPtr.Zero;
        IntPtr method;
        while ((method = Native.class_get_methods(klass, &iter)) != IntPtr.Zero)
        {
            uint implFlags = 0;
            var flags = (int)Native.method_get_flags(method, &implFlags);
            var mods = Access(flags) + ((flags & 0x10) != 0 ? " static" : "") + ((flags & 0x400) != 0 ? " abstract" : (flags & 0x40) != 0 ? " virtual" : "");
            var sb = new StringBuilder();
            var argc = Native.method_get_param_count(method);
            for (uint p = 0; p < argc; p++)
            {
                if (p > 0) sb.Append(", ");
                sb.Append(Native.TypeName(Native.method_get_param(method, p))).Append(' ').Append(Native.Str(Native.method_get_param_name(method, p)));
            }
            // The first field of the runtime's method record is the entry point; record it relative to the module.
            var pointer = *(IntPtr*)method;
            var rva = pointer == IntPtr.Zero ? "-" : "0x" + ((long)pointer - (long)Native.Module).ToString("X");
            w.WriteLine($"    {mods} {Native.TypeName(Native.method_get_return_type(method))} {Native.Str(Native.method_get_name(method))}({sb}); // RVA {rva}");
            methodCount++;
        }

        w.WriteLine("}");
        return methodCount;
    }

    private static string Access(int flags) => (flags & 0x7) switch
    {
        1 => "private",
        2 => "private protected",
        3 => "internal",
        4 => "protected",
        5 => "protected internal",
        6 => "public",
        _ => "private",
    };

    private static string BuildId(string gameDir)
    {
        var bootConfig = Path.Combine(gameDir, "PGATOUR2K25_Data", "boot.config");
        if (File.Exists(bootConfig))
            foreach (var line in File.ReadAllLines(bootConfig))
                if (line.StartsWith("build-guid=")) return line["build-guid=".Length..].Trim();
        return "unknown";
    }
}
